/// The table row of a class (Redux `ProfessionType`: Trojan 1, Warrior 2,
/// Archer 4, Taoist 10; the Water and Fire Taoists use the Taoist row).
fn row(class: u8) -> Option<usize> {
    match u16::from(class) % 1_000 / 10 {
        1 => Some(0),
        2 => Some(1),
        4 => Some(2),
        10 | 13 | 14 => Some(3),
        _ => None,
    }
}

/// (Strength, Vitality, Agility, Spirit) of `class` at `level`, capped at
/// level 120 like Redux.
pub fn for_level(class: u8, level: u16) -> Option<(u16, u16, u16, u16)> {
    let row = row(class)?;
    STATS[row].get(usize::from(level.clamp(1, 120)) - 1).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn classes_follow_the_reference_table() {
        assert_eq!(for_level(10, 1), Some((5, 3, 2, 0)));
        assert_eq!(for_level(100, 1), Some((0, 3, 2, 5)));
        assert_eq!(for_level(142, 1), for_level(100, 1));
        assert_eq!(for_level(15, 130), for_level(15, 120));
        assert_eq!(for_level(0, 10), None);
    }
}
