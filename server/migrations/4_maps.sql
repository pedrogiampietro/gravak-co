CREATE TABLE IF NOT EXISTS maps(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_id BIGINT NOT NULL,
    path TEXT NOT NULL,
    revive_point_x BIGINT NOT NULL,
    revive_point_y BIGINT NOT NULL,
    flags BIGINT NOT NULL DEFAULT 0,
    weather BIGINT NOT NULL DEFAULT 0,
    reborn_map BIGINT NOT NULL DEFAULT 0,
    color BIGINT NOT NULL DEFAULT 4294967295
);
