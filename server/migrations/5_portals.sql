CREATE TABLE IF NOT EXISTS portals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_map_id BIGINT NOT NULL CONSTRAINT fk_map_from REFERENCES maps(id) ON DELETE CASCADE,
    from_x BIGINT NOT NULL,
    from_y BIGINT NOT NULL,
    to_map_id BIGINT NOT NULL CONSTRAINT fk_map_to REFERENCES maps(id) ON DELETE CASCADE,
    to_x BIGINT NOT NULL,
    to_y BIGINT NOT NULL
);
