-- Rows inserted with their id leave the identity sequences behind (SQLite
-- numbered after the largest id by itself); this brings every sequence past
-- the largest id in use. Called after the migrations and at startup.
CREATE OR REPLACE FUNCTION sync_identity_sequences() RETURNS void AS $$
DECLARE
    col record;
    top bigint;
BEGIN
    FOR col IN
        SELECT table_name, column_name FROM information_schema.columns
        WHERE table_schema = current_schema() AND is_identity = 'YES'
    LOOP
        EXECUTE format('SELECT max(%I) FROM %I', col.column_name, col.table_name) INTO top;
        IF top IS NOT NULL THEN
            PERFORM setval(pg_get_serial_sequence(quote_ident(col.table_name), col.column_name), top);
        END IF;
    END LOOP;
    IF to_regclass('item_uid_seq') IS NOT NULL THEN
        top := 0;
        FOR col IN
            SELECT table_name FROM information_schema.columns
            WHERE table_schema = current_schema() AND column_name = 'item_uid'
              AND table_name IN ('inventory_items', 'warehouse_items', 'equipment_items', 'guild_warehouse_items')
        LOOP
            EXECUTE format('SELECT greatest(%s, coalesce(max(item_uid), 0)) FROM %I', top, col.table_name) INTO top;
        END LOOP;
        IF top > 0 THEN
            PERFORM setval('item_uid_seq', top);
        END IF;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE CHECK (length(username) <= 16),
    password TEXT NOT NULL,
    name TEXT DEFAULT NULL CHECK (length(name) <= 32),
    email TEXT DEFAULT NULL CHECK (length(email) <= 64)
);
