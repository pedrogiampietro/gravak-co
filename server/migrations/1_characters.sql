CREATE TABLE IF NOT EXISTS characters (
    character_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL CONSTRAINT fk_account REFERENCES accounts(account_id) ON DELETE CASCADE,
    realm_id BIGINT NOT NULL,
    name TEXT UNIQUE NOT NULL CHECK (length(name) <= 32),
    mesh BIGINT NOT NULL DEFAULT 1003,
    avatar BIGINT NOT NULL DEFAULT 1,
    hair_style BIGINT NOT NULL DEFAULT 535,
    silver BIGINT NOT NULL DEFAULT 1000 CHECK (silver >= 0),
    cps BIGINT NOT NULL DEFAULT 0 CHECK (cps >= 0),
    current_class BIGINT NOT NULL DEFAULT 10 CHECK (current_class > 0),
    previous_class BIGINT NOT NULL DEFAULT 0 CHECK (previous_class >= 0),
    rebirths BIGINT NOT NULL DEFAULT 0 CHECK (rebirths >= 0),
    level BIGINT NOT NULL DEFAULT 1 CHECK (level > 0),
    experience BIGINT NOT NULL DEFAULT 0 CHECK (experience >= 0),
    map_id BIGINT NOT NULL DEFAULT 1002,
    x BIGINT NOT NULL DEFAULT 430,
    y BIGINT NOT NULL DEFAULT 380,
    virtue BIGINT NOT NULL DEFAULT 0,
    strength BIGINT NOT NULL DEFAULT 4,
    agility BIGINT NOT NULL DEFAULT 6,
    vitality BIGINT NOT NULL DEFAULT 12,
    spirit BIGINT NOT NULL DEFAULT 0,
    attribute_points BIGINT NOT NULL DEFAULT 0 CHECK (attribute_points >= 0),
    health_points BIGINT NOT NULL DEFAULT 12 CHECK (health_points >= 0),
    mana_points BIGINT NOT NULL DEFAULT 0 CHECK (mana_points >= 0),
    kill_points BIGINT NOT NULL DEFAULT 0 CHECK (kill_points >= 0)
);
