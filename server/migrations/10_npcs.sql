CREATE TABLE IF NOT EXISTS npcs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  kind BIGINT NOT NULL,
  look BIGINT NOT NULL,
  map_id BIGINT NOT NULL CONSTRAINT fk_npc_map REFERENCES maps(id) ON DELETE CASCADE,
  x BIGINT NOT NULL CHECK(x >= 0),
  y BIGINT NOT NULL CHECK(y >= 0),
  base BIGINT NOT NULL,
  sort BIGINT NOT NULL,
  level BIGINT NOT NULL,
  life BIGINT NOT NULL,
  defense BIGINT NOT NULL,
  magic_defense BIGINT NOT NULL
);
