-- The Guild System window: what a guild says of itself, how it takes new
-- members, its history, its fund's movements, its wars and its dead.

-- Title (a short subtitle), motto, description, the fee new members pay
-- into the fund, whether it takes requests, and the experience its members
-- earned it (its level).
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS title TEXT NOT NULL DEFAULT '';
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS motto TEXT NOT NULL DEFAULT '';
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '';
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS entry_fee BIGINT NOT NULL DEFAULT 0 CHECK (entry_fee >= 0);
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS accepting BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE guilds ADD COLUMN IF NOT EXISTS experience BIGINT NOT NULL DEFAULT 0 CHECK (experience >= 0);

-- A character asking to join, with a message; and a guild inviting one. Both
-- last 7 days.
CREATE TABLE IF NOT EXISTS guild_requests (
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    message TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT),
    PRIMARY KEY (guild_id, character_id)
);

CREATE TABLE IF NOT EXISTS guild_invites (
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    invited_by TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT),
    PRIMARY KEY (guild_id, character_id)
);

-- What happened in a guild: founded, joined, left, kicked, promoted,
-- demoted, leader, deposit, withdraw, fee, settings, war_declared,
-- war_started, war_refused, war_ended. `amount` and `balance` (the fund
-- after) for the fund's movements. Kept 90 days.
CREATE TABLE IF NOT EXISTS guild_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    actor TEXT NOT NULL DEFAULT '',
    target TEXT NOT NULL DEFAULT '',
    amount BIGINT NOT NULL DEFAULT 0,
    balance BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);
CREATE INDEX IF NOT EXISTS idx_guild_events_guild ON guild_events(guild_id, created_at DESC);

-- A war one guild declares on another: pending until the other accepts
-- (active) or refuses; either side ends an active one.
CREATE TABLE IF NOT EXISTS guild_wars (
    war_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    enemy_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'active', 'refused', 'ended')),
    declared_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT),
    started_at BIGINT NOT NULL DEFAULT 0,
    ended_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_guild_wars_guilds ON guild_wars(guild_id, enemy_id);

-- Each kill between two guilds at war.
CREATE TABLE IF NOT EXISTS guild_war_kills (
    kill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    war_id BIGINT NOT NULL REFERENCES guild_wars(war_id) ON DELETE CASCADE,
    killer_guild_id BIGINT NOT NULL,
    killer TEXT NOT NULL,
    victim TEXT NOT NULL,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);

-- A member's death ('death') or a member's kill of another player ('frag'),
-- by a player or a monster. Kept 30 days.
CREATE TABLE IF NOT EXISTS guild_deaths (
    death_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('death', 'frag')),
    victim TEXT NOT NULL,
    victim_level INTEGER NOT NULL DEFAULT 0,
    killer TEXT NOT NULL,
    killer_guild TEXT NOT NULL DEFAULT '',
    by_player BOOLEAN NOT NULL DEFAULT FALSE,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);
CREATE INDEX IF NOT EXISTS idx_guild_deaths_guild ON guild_deaths(guild_id, created_at DESC);

-- The guilds of before keep their founding in the history.
INSERT INTO guild_events (guild_id, kind, actor, created_at)
SELECT g.guild_id, 'founded', c.name, g.created_at
FROM guilds g JOIN characters c ON c.character_id = g.leader_id
WHERE NOT EXISTS (SELECT 1 FROM guild_events e WHERE e.guild_id = g.guild_id AND e.kind = 'founded');
