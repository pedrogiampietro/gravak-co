-- The in-game Store: products sold for Conquer Points, some with a daily
-- stock shared by the server, and VIP, which belongs to the account.

ALTER TABLE accounts ADD COLUMN vip_until BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS store_products (
    product_id BIGINT PRIMARY KEY,
    -- 0 VIP, 1 Consumables, 2 Upgrades.
    category BIGINT NOT NULL CHECK (category >= 0),
    name TEXT NOT NULL CHECK (length(name) <= 40),
    description TEXT NOT NULL CHECK (length(description) <= 240),
    -- An item and how many of it, or days of VIP.
    item_type BIGINT NOT NULL DEFAULT 0,
    amount BIGINT NOT NULL DEFAULT 1 CHECK (amount BETWEEN 1 AND 40),
    vip_days BIGINT NOT NULL DEFAULT 0 CHECK (vip_days >= 0),
    price_cps BIGINT NOT NULL CHECK (price_cps > 0),
    -- Sold per day by the whole server; NULL is unlimited.
    daily_stock BIGINT CHECK (daily_stock > 0),
    sort BIGINT NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK ((item_type > 0) <> (vip_days > 0))
);

CREATE TABLE IF NOT EXISTS store_stock (
    product_id BIGINT NOT NULL REFERENCES store_products(product_id) ON DELETE CASCADE,
    -- Days since 1970 (UTC).
    day BIGINT NOT NULL,
    sold BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, day)
);

CREATE TABLE IF NOT EXISTS store_purchases (
    purchase_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES store_products(product_id),
    price_cps BIGINT NOT NULL,
    bought_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);

