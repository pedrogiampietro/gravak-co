-- Optional item progression state is kept separate from the three item
-- containers because an item can move between inventory and equipment while
-- retaining its UID. This also leaves the legacy item table layout intact.
CREATE TABLE IF NOT EXISTS item_upgrades (
    item_uid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plus BIGINT NOT NULL DEFAULT 0 CHECK (plus >= 0 AND plus <= 12),
    gem_one BIGINT NOT NULL DEFAULT 0,
    gem_two BIGINT NOT NULL DEFAULT 0,
    socket_one BIGINT NOT NULL DEFAULT 0,
    socket_two BIGINT NOT NULL DEFAULT 0,
    bless BIGINT NOT NULL DEFAULT 0,
    enchant BIGINT NOT NULL DEFAULT 0
);
