CREATE TABLE IF NOT EXISTS guilds (
    guild_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 3 AND 24),
    leader_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE RESTRICT,
    level BIGINT NOT NULL DEFAULT 1 CHECK (level > 0),
    silver BIGINT NOT NULL DEFAULT 0 CHECK (silver >= 0),
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);

CREATE TABLE IF NOT EXISTS guild_members (
    guild_id BIGINT NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    role BIGINT NOT NULL DEFAULT 0 CHECK (role >= 0),
    joined_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT),
    PRIMARY KEY (guild_id, character_id),
    UNIQUE (character_id)
);

CREATE INDEX IF NOT EXISTS idx_guild_members_character_id
    ON guild_members(character_id);

CREATE TABLE IF NOT EXISTS guild_warehouse_silver (
    guild_id BIGINT PRIMARY KEY REFERENCES guilds(guild_id) ON DELETE CASCADE,
    silver BIGINT NOT NULL DEFAULT 0 CHECK (silver >= 0)
);
