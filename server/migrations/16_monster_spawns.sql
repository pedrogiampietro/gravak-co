CREATE TABLE IF NOT EXISTS monster_spawns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monster_type_id BIGINT NOT NULL CONSTRAINT fk_monster_spawn_type REFERENCES monster_types(id) ON DELETE CASCADE,
  map_id BIGINT NOT NULL CONSTRAINT fk_monster_spawn_map REFERENCES maps(id) ON DELETE CASCADE,
  x BIGINT NOT NULL CHECK(x >= 0),
  y BIGINT NOT NULL CHECK(y >= 0),
  amount BIGINT NOT NULL DEFAULT 1 CHECK(amount >= 1),
  radius BIGINT NOT NULL DEFAULT 0 CHECK(radius >= 0)
);