CREATE TABLE IF NOT EXISTS quest_definitions (
    quest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    npc_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    target_monster_type BIGINT NOT NULL,
    required_count BIGINT NOT NULL CHECK (required_count > 0),
    reward_silver BIGINT NOT NULL DEFAULT 0 CHECK (reward_silver >= 0),
    reward_experience BIGINT NOT NULL DEFAULT 0 CHECK (reward_experience >= 0)
);

CREATE TABLE IF NOT EXISTS character_quests (
    character_id BIGINT NOT NULL CONSTRAINT fk_character_quest_character REFERENCES characters(character_id) ON DELETE CASCADE,
    quest_id BIGINT NOT NULL CONSTRAINT fk_character_quest_definition REFERENCES quest_definitions(quest_id) ON DELETE CASCADE,
    progress BIGINT NOT NULL DEFAULT 0 CHECK (progress >= 0),
    state BIGINT NOT NULL DEFAULT 1 CHECK (state IN (1, 2)),
    started_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT),
    completed_at BIGINT,
    PRIMARY KEY (character_id, quest_id)
);

