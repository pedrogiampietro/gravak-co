ALTER TABLE characters ADD COLUMN IF NOT EXISTS created_at BIGINT NOT NULL DEFAULT 0;
ALTER TABLE characters ALTER COLUMN created_at SET DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT);

-- Each day a character plays (UTC), its experience over all levels when
-- first seen that day and when last seen: the Powergamers ranking and the
-- character's experience history.
CREATE TABLE IF NOT EXISTS experience_days (
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    day DATE NOT NULL,
    start_total BIGINT NOT NULL CHECK (start_total >= 0),
    end_total BIGINT NOT NULL CHECK (end_total >= 0),
    start_level INTEGER NOT NULL,
    end_level INTEGER NOT NULL,
    rebirths INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (character_id, day)
);
CREATE INDEX IF NOT EXISTS idx_experience_days_day ON experience_days(day);

-- Every death outside the arena and the events: by whom (a player's
-- character, or a monster's name), at which level, where and when.
CREATE TABLE IF NOT EXISTS character_deaths (
    death_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(character_id) ON DELETE CASCADE,
    level INTEGER NOT NULL,
    killer_name TEXT NOT NULL,
    killer_id BIGINT REFERENCES characters(character_id) ON DELETE SET NULL,
    killer_level INTEGER,
    map_id BIGINT NOT NULL,
    died_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM now())::BIGINT)
);
CREATE INDEX IF NOT EXISTS idx_character_deaths_character ON character_deaths(character_id, died_at DESC);
CREATE INDEX IF NOT EXISTS idx_character_deaths_killer ON character_deaths(killer_id, died_at DESC);
CREATE INDEX IF NOT EXISTS idx_character_deaths_time ON character_deaths(died_at DESC);
