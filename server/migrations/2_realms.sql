CREATE TABLE IF NOT EXISTS realms (
    realm_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL CHECK (length(name) <= 16),
    game_ip_address TEXT NOT NULL CHECK (length(game_ip_address) <= 16),
    game_port BIGINT NOT NULL CHECK (
        game_port >= 0
        AND game_port <= 65535
    )
);

-- Characters were created before realms; their realm is checked from here.
ALTER TABLE characters
    ADD CONSTRAINT fk_realm FOREIGN KEY (realm_id) REFERENCES realms(realm_id);
