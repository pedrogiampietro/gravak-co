CREATE TABLE IF NOT EXISTS monster_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  look BIGINT NOT NULL,
  level BIGINT NOT NULL CHECK(level >= 1),
  life BIGINT NOT NULL CHECK(life >= 1),
  attack_min BIGINT NOT NULL CHECK(attack_min >= 0),
  attack_max BIGINT NOT NULL CHECK(attack_max >= attack_min),
  defense BIGINT NOT NULL CHECK(defense >= 0),
  attack_speed BIGINT NOT NULL CHECK(attack_speed >= 0),
  respawn_seconds BIGINT NOT NULL CHECK(respawn_seconds >= 0)
);