-- What a new character finds in its bag, besides the coat it wears: a weapon
-- of its class it can use from the first levels and some potions. `class`
-- is the class chosen at creation (10 Trojan, 20 Warrior, 40 Archer, 100
-- Taoist), NULL for every class; each row gives `amount` items. Edit the
-- rows to change the gift: it is read at each creation.
CREATE TABLE IF NOT EXISTS starter_items (
    starter_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class INT CHECK (class IN (10, 20, 40, 100)),
    item_type BIGINT NOT NULL,
    amount INT NOT NULL DEFAULT 1 CHECK (amount BETWEEN 1 AND 20),
    sort INT NOT NULL DEFAULT 0
);

